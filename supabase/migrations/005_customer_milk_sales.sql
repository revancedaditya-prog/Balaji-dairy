create or replace view public.customer_ledger_summary
with (security_invoker = true)
as
select
  c.id as customer_id,
  c.customer_code,
  c.customer_name,
  c.mobile,
  c.address,
  c.village,
  c.customer_type,
  c.billing_cycle,
  c.default_rate_per_liter,
  c.default_morning_qty,
  c.default_evening_qty,
  c.opening_balance,
  c.status,
  coalesce(d.total_liters, 0)::numeric(14,3) as total_liters,
  coalesce(d.total_sales, 0)::numeric(14,2) as total_sales,
  coalesce(p.total_paid, 0)::numeric(14,2) as total_paid,
  (c.opening_balance + coalesce(d.total_sales, 0) - coalesce(p.total_paid, 0))::numeric(14,2) as outstanding_amount
from public.customers c
left join (
  select customer_id,
         sum(quantity_liters) filter (where delivery_status = 'Delivered') as total_liters,
         sum(amount) filter (where delivery_status = 'Delivered') as total_sales
  from public.customer_milk_deliveries
  group by customer_id
) d on d.customer_id = c.id
left join (
  select customer_id, sum(amount_paid) as total_paid
  from public.customer_payments
  group by customer_id
) p on p.customer_id = c.id;

grant select on public.customer_ledger_summary to authenticated;
