create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  customer_code bigint generated by default as identity unique,
  customer_name text not null,
  mobile text,
  address text,
  village text,
  customer_type text not null default 'Household' check (customer_type in ('Household','Shop','Hotel','Restaurant','Institution','Other')),
  default_rate_per_liter numeric(10,2) not null default 0 check (default_rate_per_liter >= 0),
  default_morning_qty numeric(10,3) not null default 0 check (default_morning_qty >= 0),
  default_evening_qty numeric(10,3) not null default 0 check (default_evening_qty >= 0),
  billing_cycle text not null default 'Monthly' check (billing_cycle in ('Daily','Weekly','10 Day','Monthly','Manual')),
  opening_balance numeric(12,2) not null default 0,
  status text not null default 'active' check (status in ('active','inactive')),
  start_date date not null default (timezone('Asia/Kolkata', now()))::date,
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customer_milk_deliveries (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customers(id) on delete restrict,
  delivery_date date not null default (timezone('Asia/Kolkata', now()))::date,
  shift public.shift_type not null,
  milk_type text not null default 'Mixed' check (milk_type in ('Cow','Buffalo','Mixed','Other')),
  quantity_liters numeric(10,3) not null check (quantity_liters > 0),
  rate_per_liter numeric(10,2) not null check (rate_per_liter >= 0),
  amount numeric(12,2) generated always as (round(quantity_liters * rate_per_liter, 2)) stored,
  delivery_status text not null default 'Delivered' check (delivery_status in ('Delivered','Skipped','Returned')),
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customer_payments (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customers(id) on delete restrict,
  payment_date date not null default (timezone('Asia/Kolkata', now()))::date,
  amount_paid numeric(12,2) not null check (amount_paid > 0),
  payment_mode text not null default 'Cash' check (payment_mode in ('Cash','UPI','Bank Transfer','Cheque','Other')),
  reference_no text,
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_customers_status on public.customers(status);
create index if not exists idx_customers_name on public.customers(customer_name);
create index if not exists idx_customer_deliveries_customer_date on public.customer_milk_deliveries(customer_id, delivery_date desc);
create index if not exists idx_customer_deliveries_date_shift on public.customer_milk_deliveries(delivery_date desc, shift);
create index if not exists idx_customer_payments_customer_date on public.customer_payments(customer_id, payment_date desc);

create trigger customers_set_updated_at before update on public.customers for each row execute function public.set_updated_at();
create trigger customer_deliveries_set_updated_at before update on public.customer_milk_deliveries for each row execute function public.set_updated_at();
create trigger customer_payments_set_updated_at before update on public.customer_payments for each row execute function public.set_updated_at();

alter table public.customers enable row level security;
alter table public.customer_milk_deliveries enable row level security;
alter table public.customer_payments enable row level security;

